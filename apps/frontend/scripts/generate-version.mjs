import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const repoRoot = join(import.meta.dirname, '..', '..');
const outFile = join(import.meta.dirname, '..', 'src/app/core/version/version.ts');

let version = 'V0.0.0';
try {
  version = execSync('git describe --tags --always', {
    cwd: repoRoot,
    encoding: 'utf8',
  }).trim();
} catch {
  // git not available (e.g. shallow CI checkout); fall back to placeholder.
}

// Normalize: strip leading 'v' if present, keep 'V' prefix for display.
const displayVersion = version.startsWith('v') ? `V${version.slice(1)}` : version;

const content = `// Auto-generated by scripts/generate-version.mjs — do not edit by hand.
// Source: \`git describe --tags --always\` at build time.
export const APP_VERSION = '${displayVersion}';
`;

writeFileSync(outFile, content);
console.log(`Generated ${outFile} -> APP_VERSION = ${displayVersion}`);