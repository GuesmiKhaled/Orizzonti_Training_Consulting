// Lists the pictures in the repository's img/ folder so the admin can choose one
// for a language. A browser cannot list a folder at runtime, so this runs before
// start, build and test (see package.json) and writes a TypeScript file.
//
//   node scripts/generate-image-library.mjs          write the file
//   node scripts/generate-image-library.mjs --check  exit 1 if it is out of date
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const imgRoot = resolve(here, '../../../img');
const output = resolve(here, '../src/app/shared/image-library/image-library.generated.ts');

const EXTENSIONS = /\.(jpe?g|png|gif|webp)$/i;
// Must stay in sync with IMAGE_LIBRARY_PATH in apps/backend/src/language/image-library-path.ts
const ALLOWED_PATH = /^(?!.*\.\.)(?!.*\/\/)\/img\/[\p{L}\p{N}_\-./ ]+\.(jpe?g|png|gif|webp)$/iu;
// UI furniture, not pictures to pick for a language.
const SKIP_FOLDERS = new Set(['icons']);
const SKIP_FILES = /^(loader|triangle|timer_bg|log_orizzonti)/i;

function* walk(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const full = join(directory, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_FOLDERS.has(entry.name)) {
        yield* walk(full);
      }
    } else if (EXTENSIONS.test(entry.name) && !SKIP_FILES.test(entry.name)) {
      yield full;
    }
  }
}

function build() {
  if (!existsSync(imgRoot)) {
    throw new Error(`Image folder not found: ${imgRoot}`);
  }
  const skipped = [];
  const images = [];
  for (const file of walk(imgRoot)) {
    const path = '/img/' + relative(imgRoot, file).split(sep).join('/');
    if (!ALLOWED_PATH.test(path)) {
      skipped.push(path);
      continue;
    }
    const parts = path.split('/');
    images.push({
      path,
      name: parts[parts.length - 1],
      folder: parts.slice(2, -1).join('/'),
    });
  }
  images.sort((a, b) => a.folder.localeCompare(b.folder) || a.name.localeCompare(b.name, 'en', { numeric: true }));

  const lines = images.map(
    (image) =>
      `  { path: ${JSON.stringify(image.path)}, name: ${JSON.stringify(image.name)}, folder: ${JSON.stringify(image.folder)} },`,
  );
  const source = `// Generated by scripts/generate-image-library.mjs from the img/ folder. Do not edit.
export interface LibraryImage {
  /** Site-relative path stored on the language, for example /img/cat-1.jpg. */
  readonly path: string;
  readonly name: string;
  /** Sub-folder inside img/, or an empty string for the root. */
  readonly folder: string;
}

export const IMAGE_LIBRARY: readonly LibraryImage[] = [
${lines.join('\n')}
];
`;
  return { source, count: images.length, skipped };
}

const { source, count, skipped } = build();
for (const path of skipped) {
  console.warn(`Skipped (name not allowed by the API): ${path}`);
}

if (process.argv.includes('--check')) {
  const current = existsSync(output) ? readFileSync(output, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== source) {
    console.error('image-library.generated.ts is out of date. Run: npm run images');
    process.exit(1);
  }
  console.log(`Image library is up to date (${count} images).`);
} else {
  writeFileSync(output, source, 'utf8');
  console.log(`Image library written: ${count} images.`);
}
